import { AnnotationSpec } from '../annotations'
import type { TAnnotationsTree } from '../config'
import { isAnnotate } from '../parser/nodes'
import { TSeverity } from '../parser/types'

export const emitAnnotations: TAnnotationsTree = {
  jsonSchema: new AnnotationSpec({
    nodeType: ['interface', 'type', 'annotate'],
    description:
      'Pre-compute and embed JSON Schema at build time for this interface, regardless of the global jsonSchema plugin option.',
  }),
  compiledValidator: new AnnotationSpec({
    nodeType: ['interface', 'type', 'annotate'],
    description:
      'Emit a build-time compiled validator check for this type, regardless of the global compileValidators plugin option.\n\n' +
      'Only this type gets a check (same-file types it references are compiled inside it). ' +
      'On a mutating `annotate` block, the annotated type gets one (only a type of this file). ' +
      "Ignored where a build forces interpreted output (unplugin-atscript `compileValidators: false`, or client bundles with `'ssr'`).",
    validate(token, _args, doc) {
      // A mutating annotate of an imported type: its class is generated by the module that
      // declares it, so nothing here can compile it.
      const node = token.parentNode
      if (isAnnotate(node) && node.isMutating) {
        const owner = doc.getDeclarationOwnerNode(node.targetName)
        if (owner && owner.doc !== doc) {
          return [
            {
              message: `"${node.targetName}" is declared in another file: @emit.compiledValidator has no effect on a mutating annotate of an imported type — annotate the type in its own file instead`,
              range: token.range,
              severity: TSeverity.Warning,
            },
          ]
        }
      }
      return []
    },
  }),
}
